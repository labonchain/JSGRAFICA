CREATE OR REPLACE VIEW private.jsgrafica_catalogo_publico AS
SELECT
  p.id AS produto_id,
  pub.sku,
  pub.slug,
  p.nome,
  p.categoria,
  pub.familia,
  pub.colecao_tema,
  pub.versao,
  pub.resumo_curto,
  pub.descricao_publica,
  pub.publico,
  pub.problema_resolvido,
  pub.ocasioes,
  pub.diferenciais,
  pub.narrativa_comercial,
  pub.especificacao_digital,
  pub.especificacao_fisica,
  pub.entrega,
  pub.licenca_direitos,
  pub.tags,
  pub.destaque,
  pub.seo_title,
  pub.seo_description,
  COALESCE((
    SELECT jsonb_agg(jsonb_build_object(
      'id', m.id,
      'tipo', m.tipo,
      'ativo', m.ativo,
      'conteudo_incluido', m.conteudo_incluido,
      'preco', m.preco,
      'modo_preco', m.modo_preco,
      'prazo', m.prazo,
      'dados_cliente', m.dados_cliente,
      'regras_personalizacao', m.regras_personalizacao,
      'orcamento_obrigatorio', m.orcamento_obrigatorio,
      'whatsapp_mensagem', m.whatsapp_mensagem
    ) ORDER BY m.id)
    FROM public.jsgrafica_catalogo_modalidades m
    WHERE m.publicacao_id = pub.id AND m.ativo = true
  ), '[]'::jsonb) AS modalidades,
  COALESCE((
    SELECT jsonb_agg(jsonb_build_object(
      'id', a.id,
      'tipo', a.tipo,
      'storage_bucket', a.storage_bucket,
      'storage_path', a.storage_path,
      'public_url', concat(current_setting('app.settings.supabase_url', true), '/storage/v1/object/public/', a.storage_bucket, '/', a.storage_path),
      'alt_text', a.alt_text,
      'ordem', a.ordem,
      'largura', a.largura,
      'altura', a.altura
    ) ORDER BY a.ordem, a.id)
    FROM public.jsgrafica_catalogo_assets a
    WHERE a.publicacao_id = pub.id AND a.aprovado = true AND a.publicavel = true
  ), '[]'::jsonb) AS assets
FROM public.jsgrafica_produtos p
JOIN public.jsgrafica_catalogo_publicacao pub ON pub.produto_id = p.id
WHERE p.ativo = true
  AND pub.status_produto = 'ATIVO'
  AND pub.status_publicacao = 'PUBLICADO'
  AND EXISTS (SELECT 1 FROM public.jsgrafica_catalogo_modalidades m WHERE m.publicacao_id = pub.id AND m.ativo = true)
  AND EXISTS (SELECT 1 FROM public.jsgrafica_catalogo_assets a WHERE a.publicacao_id = pub.id AND a.aprovado = true AND a.publicavel = true);

-- RPCs estritamente de leitura. O SITE chama apenas estas funções com publishable/anon key.
CREATE OR REPLACE FUNCTION public.jsgrafica_catalogo_listar(
  p_categoria text DEFAULT NULL,
  p_modalidade text DEFAULT NULL,
  p_destaque boolean DEFAULT NULL
)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, private
AS $$
  SELECT COALESCE(jsonb_agg(to_jsonb(v) ORDER BY v.destaque DESC, v.nome), '[]'::jsonb)
  FROM private.jsgrafica_catalogo_publico v
  WHERE (p_categoria IS NULL OR v.categoria = p_categoria)
    AND (p_destaque IS NULL OR v.destaque = p_destaque)
    AND (p_modalidade IS NULL OR EXISTS (
      SELECT 1 FROM jsonb_array_elements(v.modalidades) m WHERE m->>'tipo' = p_modalidade
    ));
$$;

CREATE OR REPLACE FUNCTION public.jsgrafica_catalogo_por_slug(p_slug text)
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public, private
AS $$
  SELECT to_jsonb(v) FROM private.jsgrafica_catalogo_publico v WHERE v.slug = p_slug LIMIT 1;
$$;

