-- Publicação exige contrato mínimo + gates + ao menos uma modalidade e um asset aprovados.
CREATE OR REPLACE FUNCTION public.jsgrafica_catalogo_validar_publicacao()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE op_ativo boolean;
BEGIN
  IF NEW.status_publicacao = 'PUBLICADO' THEN
    IF NEW.status_produto <> 'ATIVO' THEN
      RAISE EXCEPTION 'PUBLICAÇÃO BLOQUEADA: status_produto deve ser ATIVO';
    END IF;
    IF nullif(trim(NEW.status_produto_referencia),'') IS NULL THEN
      RAISE EXCEPTION 'PUBLICAÇÃO BLOQUEADA: status_produto_referencia deve apontar para o handoff/decisão de PRODUTOS';
    END IF;
    IF nullif(trim(NEW.sku),'') IS NULL OR nullif(trim(NEW.slug),'') IS NULL OR nullif(trim(NEW.versao),'') IS NULL
       OR nullif(trim(NEW.resumo_curto),'') IS NULL OR nullif(trim(NEW.descricao_publica),'') IS NULL
       OR nullif(trim(NEW.seo_title),'') IS NULL OR nullif(trim(NEW.seo_description),'') IS NULL THEN
      RAISE EXCEPTION 'PUBLICAÇÃO BLOQUEADA: campos públicos obrigatórios ausentes';
    END IF;

    SELECT ativo INTO op_ativo FROM public.jsgrafica_produtos WHERE id = NEW.produto_id;
    IF op_ativo IS DISTINCT FROM true THEN
      RAISE EXCEPTION 'PUBLICAÇÃO BLOQUEADA: produto operacional não está ativo';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM public.jsgrafica_catalogo_modalidades m WHERE m.publicacao_id = NEW.id AND m.ativo = true) THEN
      RAISE EXCEPTION 'PUBLICAÇÃO BLOQUEADA: nenhuma modalidade ativa';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.jsgrafica_catalogo_assets a WHERE a.publicacao_id = NEW.id AND a.aprovado = true AND a.publicavel = true) THEN
      RAISE EXCEPTION 'PUBLICAÇÃO BLOQUEADA: nenhum asset aprovado/publicável';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_catalogo_validar_publicacao ON public.jsgrafica_catalogo_publicacao;
CREATE TRIGGER trg_catalogo_validar_publicacao
BEFORE INSERT OR UPDATE OF status_publicacao, status_produto, status_produto_referencia, produto_id, sku, slug, versao, resumo_curto, descricao_publica, seo_title, seo_description
ON public.jsgrafica_catalogo_publicacao
FOR EACH ROW EXECUTE FUNCTION public.jsgrafica_catalogo_validar_publicacao();

-- Impede remover o último gate filho de uma publicação já PUBLICADA.
CREATE OR REPLACE FUNCTION public.jsgrafica_catalogo_validar_integridade_filhos()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE pub_id bigint;
DECLARE pub_status text;
BEGIN
  IF TG_OP = 'DELETE' THEN
    pub_id := OLD.publicacao_id;
  ELSE
    pub_id := NEW.publicacao_id;
  END IF;
  SELECT status_publicacao INTO pub_status FROM public.jsgrafica_catalogo_publicacao WHERE id = pub_id;
  IF pub_status = 'PUBLICADO' THEN
    IF TG_TABLE_NAME = 'jsgrafica_catalogo_modalidades' AND NOT EXISTS (
      SELECT 1 FROM public.jsgrafica_catalogo_modalidades WHERE publicacao_id = pub_id AND ativo = true
    ) THEN
      RAISE EXCEPTION 'ALTERAÇÃO BLOQUEADA: publicação ficaria sem modalidade ativa';
    END IF;
    IF TG_TABLE_NAME = 'jsgrafica_catalogo_assets' AND NOT EXISTS (
      SELECT 1 FROM public.jsgrafica_catalogo_assets WHERE publicacao_id = pub_id AND aprovado = true AND publicavel = true
    ) THEN
      RAISE EXCEPTION 'ALTERAÇÃO BLOQUEADA: publicação ficaria sem asset aprovado/publicável';
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_catalogo_modalidades_integridade ON public.jsgrafica_catalogo_modalidades;
CREATE CONSTRAINT TRIGGER trg_catalogo_modalidades_integridade AFTER INSERT OR UPDATE OR DELETE ON public.jsgrafica_catalogo_modalidades DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION public.jsgrafica_catalogo_validar_integridade_filhos();
DROP TRIGGER IF EXISTS trg_catalogo_assets_integridade ON public.jsgrafica_catalogo_assets;
CREATE CONSTRAINT TRIGGER trg_catalogo_assets_integridade AFTER INSERT OR UPDATE OR DELETE ON public.jsgrafica_catalogo_assets DEFERRABLE INITIALLY IMMEDIATE FOR EACH ROW EXECUTE FUNCTION public.jsgrafica_catalogo_validar_integridade_filhos();

